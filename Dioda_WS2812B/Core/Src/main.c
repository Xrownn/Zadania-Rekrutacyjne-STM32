/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  uint32_t last_ms = HAL_GetTick(); //odczytanie aktualnego czasu
  uint32_t last_ms_blue = last_ms;
  ws2812b_init();
  //ustawienie zmiennych odpowiadajacych za kolory
  uint8_t red = 255;
  uint8_t green = 0;
  uint8_t blue = 0;
  uint8_t blue_count = 0;
  uint8_t blue_state = 0;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	  uint32_t now = HAL_GetTick();

	  if ((now-last_ms)>=3000)
		  last_ms = now;

	  uint32_t t = now - last_ms;

	  // realizacja sygnału prostokątnego z wypełnieniem 50% - 0-1500ms - dioda red świeci, 1500-3000ms nie świeci
	  red = (t<1500) ? 255:0;

	  // realizacja sygnału piłokształtnego - natężenie diody ciągle rośnie aż do wyzerowania t gdzie przyjmuje wartości zbliżone do zera
	  green = t*255/3000;

	  // odczytanie naciśniecia przycisku oraz zapobieganie ponownemu kliknieciu przed zakonczeniem cyklu
	  if (HAL_GPIO_ReadPin(Button_B_GPIO_Port, Button_B_Pin) == GPIO_PIN_RESET && blue_count == 0){
		  blue_count = 6;
	  	  blue_state = 1;
	  	  last_ms_blue = now;
	  }
	  // sekwencja 6 cykli 255->0->255->0->255->0 realizująca miganie
	  if (blue_count !=0 && now - last_ms_blue >= 250 ){
		  if (blue_state == 1)
			  blue = 255;
		  else
			  blue = 0;
		  blue_state=!blue_state;
		  last_ms_blue = now;
		  blue_count --;
  	  }
	  // w razie czego żeby blue napewno zgasł chociaż w 6 cyklach powinien zgasnac i tak
	  if (blue_count == 0) {
	      blue = 0;
	  }

	  // ustawienie kolorow do bufforu kazdego leda
	  for (int led_n = 0; led_n<LED_N; led_n++){
		  ws2812b_set_color(led_n, green, red, blue);
	  }

	  ws2812b_update();
  }
  /* USER CODE END 3 */
}

