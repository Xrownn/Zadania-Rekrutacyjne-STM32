/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  /* USER CODE BEGIN 2 */

  //rozpoczęcie ciągłęgo pomiaru ADC za pomocą DMA
  HAL_ADCEx_Calibration_Start(&hadc1, ADC_SINGLE_ENDED);
  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)value, 1);
  uint8_t selected_mode = 1; //zmienna wyznaczająca aktualną mierzoną wartość: 1 - wilgoć, 2 - pH, 3 - temperatura
  uint32_t trg_timer = 0;
  uint8_t trg_status = 0;
  uint8_t measurement_status = 0; //zmienna oznaczająca trwający pomiar

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */
    /* USER CODE BEGIN 3 */
	uint32_t now = HAL_GetTick();

	//ustawianie mierzonego parametru
	if(measurement_status == 0){
		switch(selected_mode){
		case 1:
			spx25_set_mode(0,0); //pomiar wilgoci
			break;
		case 2:
			spx25_set_mode(0, 1); //pomiar pH
			break;
		case 3:
			spx25_set_mode(1, 0); //pomiar temperatury
			break;
		}
		// ustawienie sygnału trg
		HAL_GPIO_WritePin(TRG_SP_GPIO_Port, TRG_SP_Pin, GPIO_PIN_SET);
		trg_timer = HAL_GetTick();
		trg_status = 1;
		measurement_status = 1;
	}
	//zakończenie nadawania sygnału trg po 10ms
	if(trg_status == 1 && (now - trg_timer)> 10){
		trg_status = 0;
		HAL_GPIO_WritePin(TRG_SP_GPIO_Port, TRG_SP_Pin, GPIO_PIN_RESET);
	}
    //warunek sprawdzający czy sensor skończył pomiar, warunek trg_status == 0 przecwdziała sytuacji gdyby sensor wystawiał jakiś wynik podczas gdy my zlecamy kolejny
	if(HAL_GPIO_ReadPin(DR_SP_GPIO_Port, DR_SP_Pin) == GPIO_PIN_SET && trg_status == 0){
		spx25_measurement_conversion(selected_mode,value[0]);
		measurement_status = 0;
		selected_mode++;
		if(selected_mode>3)
			selected_mode = 1;
	}
	//warunek resetujący pomiar gdy trwa on dłużej niż najwięcej przewidziane 500ms
	if(measurement_status == 1 && (now - trg_timer) > 500){
	    measurement_status = 0;
	}
  }
  /* USER CODE END 3 */
}

